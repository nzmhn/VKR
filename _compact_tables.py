def replace_tables(text: str) -> tuple[str, list[str]]:
    lines = text.splitlines()
    replaced: list[str] = []
    i = 0
    out: list[str] = []
    while i < len(lines):
        m = re.match(r"^Таблица (\d+(?:\.\d+){1,2})\b", lines[i].strip())
        if m and m.group(1) in NEW_TABLES:
            num = m.group(1)
            cap = i
            j = i + 1
            while j < len(lines) and not lines[j].startswith("|"):
                j += 1
            if j == len(lines):
                out.append(lines[i])
                i += 1
                continue
            bs = j
            while j < len(lines) and lines[j].startswith("|"):
                j += 1
            be = j - 1
            # сохранить шапку: подпись и название без изменений
            out.extend(lines[cap:bs])
            out.extend(NEW_TABLES[num].splitlines())
            replaced.append(num)
            i = be + 1
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out) + ("\n" if text.endswith("\n") else ""), replaced


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    new_text, replaced = replace_tables(text)
    SRC.write_text(new_text, encoding="utf-8")
    print(f"Заменены таблицы ({len(replaced)}): {', '.join(replaced)}")
    print(f"Размер файла: {SRC.stat().st_size:,} байт")


if __name__ == "__main__":
    main()
