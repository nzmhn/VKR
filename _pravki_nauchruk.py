def splice(start_anchor: str, end_anchor: str, new_block: str) -> None:
    """Заменить участок [start_anchor .. end_anchor] (включительно) на new_block."""
    global content
    si = content.find(start_anchor)
    assert si != -1, f"НЕ НАЙДЕН старт: {start_anchor[:50]!r}"
    ei = content.find(end_anchor, si)
    assert ei != -1, f"НЕ НАЙДЕН конец: {end_anchor[:50]!r}"
    ei += len(end_anchor)
    content = content[:si] + new_block + content[ei:]


def rep(old: str, new: str, n: int = 1) -> None:
    """Точная замена с проверкой числа вхождений."""
    global content
    c = content.count(old)
    assert c == n, f"ОЖИДАЛОСЬ {n}, НАЙДЕНО {c}: {old[:60]!r}"
    content = content.replace(old, new)


